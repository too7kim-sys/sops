CREATE TABLE IF NOT EXISTS OPS_APPR_LINE (
    APPR_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    BIZ_TYPE    VARCHAR(20)  NOT NULL,           -- CHANGE/RELEASE/CSR/INCIDENT/PROBLEM/TEST/INTERFACE/CI/EVENT
