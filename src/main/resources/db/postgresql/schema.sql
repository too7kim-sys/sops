    TITLE      VARCHAR(200)  NOT NULL,
    PARTNER_SYS VARCHAR(100),
    IF_TYPE    VARCHAR(20)   NOT NULL,
    DATA_DESC  VARCHAR(2000),
    STATUS     VARCHAR(20)   NOT NULL,
    REQ_ID     VARCHAR(20),
    REQ_DT     TIMESTAMP,
    CHARGER_ID VARCHAR(20),
    PLAN_DT    DATE,
    COMPLETE_DT TIMESTAMP,
    RESULT     VARCHAR(1000),
    REG_DT     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_INTERFACE PRIMARY KEY (INTF_ID)
);
CREATE TABLE IF NOT EXISTS OPS_INTERFACE_HIS (
    HIS_ID   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    INTF_ID  BIGINT       NOT NULL,
    STATUS   VARCHAR(20)  NOT NULL,
    CONTENT  VARCHAR(2000),
    PROC_ID  VARCHAR(20),
    PROC_DT  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_INTERFACE_HIS PRIMARY KEY (HIS_ID)
);

-- ⑥ 형상관리
CREATE TABLE IF NOT EXISTS OPS_CI (
    CI_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
