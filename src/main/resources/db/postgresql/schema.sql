-- =====================================================================
-- 범정부 응용프로그램 운영관리시스템 (eGov-Ops) — 운영(PostgreSQL) 스키마
-- 비파괴적 DDL : CREATE TABLE IF NOT EXISTS (기동 시 반복 적용 안전)
-- =====================================================================

-- 사용자(운영자) -------------------------------------------------------
CREATE TABLE IF NOT EXISTS OPS_USER (
    USER_ID    VARCHAR(20)   NOT NULL,
    USER_NM    VARCHAR(50)   NOT NULL,
    PASSWORD   VARCHAR(100)  NOT NULL,
    ROLE       VARCHAR(20)   NOT NULL,
    DEPT_NM    VARCHAR(100),
    EMAIL      VARCHAR(100),
    TELNO      VARCHAR(20),
    USE_AT     CHAR(1)       DEFAULT 'Y',
    REG_DT     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_USER PRIMARY KEY (USER_ID)
);

-- 응용시스템(운영대상) 마스터 -----------------------------------------
CREATE TABLE IF NOT EXISTS OPS_SYSTEM (
    SYS_ID     VARCHAR(20)   NOT NULL,
    SYS_NM     VARCHAR(100)  NOT NULL,
    SYS_DESC   VARCHAR(500),
    MNGR_NM    VARCHAR(50),
    MNGR_DEPT  VARCHAR(100),
    GRAD       VARCHAR(20),
    USE_AT     CHAR(1)       DEFAULT 'Y',
    REG_DT     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_SYSTEM PRIMARY KEY (SYS_ID)
);

-- 공통코드 ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS OPS_CODE (
    CODE_GRP   VARCHAR(30)   NOT NULL,
    CODE_ID    VARCHAR(30)   NOT NULL,
    CODE_NM    VARCHAR(100)  NOT NULL,
    SORT_ORDR  INT           DEFAULT 1,
    USE_AT     CHAR(1)       DEFAULT 'Y',
    CONSTRAINT PK_OPS_CODE PRIMARY KEY (CODE_GRP, CODE_ID)
);

-- 장애관리 ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS OPS_INCIDENT (
    INC_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID     VARCHAR(20)   NOT NULL,
    TITLE      VARCHAR(200)  NOT NULL,
    CONTENT    VARCHAR(2000),
    SEVERITY   VARCHAR(10)   NOT NULL,
    STATUS     VARCHAR(20)   NOT NULL,
    OCCR_DT    TIMESTAMP,
    RCPT_DT    TIMESTAMP,
    RESOLVE_DT TIMESTAMP,
    CAUSE      VARCHAR(2000),
    ACTION     VARCHAR(2000),
    CHARGER_ID VARCHAR(20),
    REG_ID     VARCHAR(20),
    REG_DT     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_INCIDENT PRIMARY KEY (INC_ID)
);

-- 장애 처리이력 -------------------------------------------------------
CREATE TABLE IF NOT EXISTS OPS_INCIDENT_HIS (
    HIS_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    INC_ID     BIGINT        NOT NULL,
    STATUS     VARCHAR(20)   NOT NULL,
    CONTENT    VARCHAR(2000),
    PROC_ID    VARCHAR(20),
    PROC_DT    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_INCIDENT_HIS PRIMARY KEY (HIS_ID)
);

-- 변경관리 ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS OPS_CHANGE (
    CHG_ID       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID       VARCHAR(20)  NOT NULL,
    TITLE        VARCHAR(200) NOT NULL,
    CHG_TYPE     VARCHAR(20)  NOT NULL,
    REASON       VARCHAR(2000),
    CONTENT      VARCHAR(2000),
    STATUS       VARCHAR(20)  NOT NULL,
    REQ_ID       VARCHAR(20),
    REQ_DT       TIMESTAMP,
    APPR_ID      VARCHAR(20),
    APPR_DT      TIMESTAMP,
    APPR_OPINION VARCHAR(1000),
    PLAN_DT      DATE,
    APPLY_DT     TIMESTAMP,
    REG_DT       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CHANGE PRIMARY KEY (CHG_ID)
);

-- 배포(릴리즈)관리 ----------------------------------------------------
CREATE TABLE IF NOT EXISTS OPS_RELEASE (
    REL_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID     VARCHAR(20)   NOT NULL,
    CHG_ID     BIGINT,
    VER        VARCHAR(30)   NOT NULL,
    TITLE      VARCHAR(200)  NOT NULL,
    CONTENT    VARCHAR(2000),
    STATUS     VARCHAR(20)   NOT NULL,
    PLAN_DT    TIMESTAMP,
    DEPLOY_DT  TIMESTAMP,
    CHARGER_ID VARCHAR(20),
    RESULT     VARCHAR(1000),
    REG_DT     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_RELEASE PRIMARY KEY (REL_ID)
);

-- 운영점검(일일/정기) -------------------------------------------------
CREATE TABLE IF NOT EXISTS OPS_CHECK (
    CHK_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID     VARCHAR(20)   NOT NULL,
    CHK_TYPE   VARCHAR(20)   NOT NULL,
    CHK_DT     DATE          NOT NULL,
    CHKR_ID    VARCHAR(20),
    RESULT     VARCHAR(20)   NOT NULL,
    REMARK     VARCHAR(1000),
    REG_DT     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CHECK PRIMARY KEY (CHK_ID)
);

-- 운영점검 항목별 결과 ------------------------------------------------
CREATE TABLE IF NOT EXISTS OPS_CHECK_ITEM (
    ITEM_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CHK_ID      BIGINT       NOT NULL,
    ITEM_NM     VARCHAR(200) NOT NULL,
    ITEM_RESULT VARCHAR(20)  NOT NULL,
    ITEM_REMARK VARCHAR(500),
    CONSTRAINT PK_OPS_CHECK_ITEM PRIMARY KEY (ITEM_ID)
);

-- =====================================================================
-- 표준운영절차 확장 모듈 (요청/테스트/연계/형상/운영상태/문제)
-- =====================================================================

-- ① 요청관리 (CSR)
CREATE TABLE IF NOT EXISTS OPS_CSR (
    CSR_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID      VARCHAR(20)   NOT NULL,
    TITLE       VARCHAR(200)  NOT NULL,
    CONTENT     VARCHAR(2000),
    CSR_TYPE    VARCHAR(20)   NOT NULL,
    PRIORITY    VARCHAR(20),
    STATUS      VARCHAR(20)   NOT NULL,
    REQ_ID      VARCHAR(20),
    REQ_DT      TIMESTAMP,
    CHARGER_ID  VARCHAR(20),
    PROC_CONTENT VARCHAR(2000),
    PROC_DT     TIMESTAMP,
    LINKED_TYPE VARCHAR(20),
    LINKED_ID   BIGINT,
    SATISFACTION VARCHAR(10),
    REG_DT      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CSR PRIMARY KEY (CSR_ID)
);
CREATE TABLE IF NOT EXISTS OPS_CSR_HIS (
    HIS_ID   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CSR_ID   BIGINT       NOT NULL,
    STATUS   VARCHAR(20)  NOT NULL,
    CONTENT  VARCHAR(2000),
    PROC_ID  VARCHAR(20),
    PROC_DT  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CSR_HIS PRIMARY KEY (HIS_ID)
);

-- ④ 테스트관리
CREATE TABLE IF NOT EXISTS OPS_TEST (
    TEST_ID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID     VARCHAR(20)   NOT NULL,
    CHG_ID     BIGINT,
    TITLE      VARCHAR(200)  NOT NULL,
    TEST_TYPE  VARCHAR(20)   NOT NULL,
    TEST_ENV   VARCHAR(20)   NOT NULL,
    STATUS     VARCHAR(20)   NOT NULL,
    PLAN_DT    DATE,
    TESTER_ID  VARCHAR(20),
    RESULT_SUMMARY VARCHAR(2000),
    REG_DT     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_TEST PRIMARY KEY (TEST_ID)
);
CREATE TABLE IF NOT EXISTS OPS_TEST_CASE (
    CASE_ID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    TEST_ID    BIGINT       NOT NULL,
    CASE_NM    VARCHAR(200) NOT NULL,
    EXPECTED   VARCHAR(500),
    CASE_RESULT VARCHAR(20) NOT NULL,
    REMARK     VARCHAR(500),
    CONSTRAINT PK_OPS_TEST_CASE PRIMARY KEY (CASE_ID)
);

-- ⑤ 연계관리
CREATE TABLE IF NOT EXISTS OPS_INTERFACE (
    INTF_ID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
