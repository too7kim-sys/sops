    CI_NM      VARCHAR(200)  NOT NULL,
    CI_TYPE    VARCHAR(20)   NOT NULL,
    VER        VARCHAR(30),
    CI_STATUS  VARCHAR(20)   NOT NULL,
    LOCATION   VARCHAR(300),
    OWNER_ID   VARCHAR(20),
    CI_DESC    VARCHAR(1000),
