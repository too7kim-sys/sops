    CSR_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID      VARCHAR(20)   NOT NULL,
    TITLE       VARCHAR(200)  NOT NULL,
    CONTENT     VARCHAR(8000),
    CSR_TYPE    VARCHAR(20)   NOT NULL,   -- 요청 대분류 (GENERAL/INCIDENT/CHANGE/BACKUP/CONFIG)
    CSR_SUB_TYPE VARCHAR(30),             -- 요청 소분류 (CSR_SUBTYPE 코드)
    PRIORITY    VARCHAR(20),
    STATUS      VARCHAR(20)   NOT NULL,
    REQ_ID      VARCHAR(20),
    REQ_DT      TIMESTAMP,
    DUE_DT      DATE,                     -- 완료요구일
    CHARGER_ID  VARCHAR(20),
    PROC_CONTENT VARCHAR(8000),
    PROC_DT     TIMESTAMP,
    LINKED_TYPE VARCHAR(20),
    LINKED_ID   BIGINT,
    SATISFACTION VARCHAR(10),
    REG_DT      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CSR PRIMARY KEY (CSR_ID)
);
CREATE TABLE IF NOT EXISTS OPS_CSR_HIS (
