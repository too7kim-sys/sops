-- ⑦ 운영상태관리 (모니터링 이벤트)
CREATE TABLE IF NOT EXISTS OPS_EVENT (
    EVT_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID     VARCHAR(20)   NOT NULL,
    TITLE      VARCHAR(200)  NOT NULL,
    EVT_TYPE   VARCHAR(20)   NOT NULL,
    SEVERITY   VARCHAR(20)   NOT NULL,
    STATUS     VARCHAR(20)   NOT NULL,
    OCCR_DT    TIMESTAMP,
    CONTENT    VARCHAR(2000),
    ACTION     VARCHAR(2000),
    CHARGER_ID VARCHAR(20),
    LINKED_INC_ID BIGINT,
    REG_DT     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_EVENT PRIMARY KEY (EVT_ID)
);
CREATE TABLE IF NOT EXISTS OPS_EVENT_HIS (
    HIS_ID   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    EVT_ID   BIGINT       NOT NULL,
    STATUS   VARCHAR(20)  NOT NULL,
    CONTENT  VARCHAR(2000),
    PROC_ID  VARCHAR(20),
    PROC_DT  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_EVENT_HIS PRIMARY KEY (HIS_ID)
);

-- ⑨ 문제관리 (+ 장애연계 + KEDB)
CREATE TABLE IF NOT EXISTS OPS_PROBLEM (
    PRB_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID     VARCHAR(20)   NOT NULL,
    TITLE      VARCHAR(200)  NOT NULL,
    CONTENT    VARCHAR(2000),
    PRIORITY   VARCHAR(20),
    STATUS     VARCHAR(20)   NOT NULL,
    ROOT_CAUSE VARCHAR(2000),
    SOLUTION   VARCHAR(2000),
    REG_ID     VARCHAR(20),
    REG_DT     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CHARGER_ID VARCHAR(20),
    RESOLVE_DT TIMESTAMP,
    CONSTRAINT PK_OPS_PROBLEM PRIMARY KEY (PRB_ID)
);
CREATE TABLE IF NOT EXISTS OPS_PROBLEM_HIS (
    HIS_ID   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRB_ID   BIGINT       NOT NULL,
    STATUS   VARCHAR(20)  NOT NULL,
    CONTENT  VARCHAR(2000),
    PROC_ID  VARCHAR(20),
    PROC_DT  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_PROBLEM_HIS PRIMARY KEY (HIS_ID)
);
CREATE TABLE IF NOT EXISTS OPS_PROBLEM_INC (
    PRB_ID   BIGINT       NOT NULL,
    INC_ID   BIGINT       NOT NULL,
    CONSTRAINT PK_OPS_PROBLEM_INC PRIMARY KEY (PRB_ID, INC_ID)
);
CREATE TABLE IF NOT EXISTS OPS_KEDB (
    KEDB_ID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRB_ID     BIGINT,
    TITLE      VARCHAR(200)  NOT NULL,
    SYMPTOM    VARCHAR(2000),
    CAUSE      VARCHAR(2000),
    WORKAROUND VARCHAR(2000),
    SOLUTION   VARCHAR(2000),
    REG_DT     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_KEDB PRIMARY KEY (KEDB_ID)
);
