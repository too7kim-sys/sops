    ORIGIN_NM    VARCHAR(260) NOT NULL,    -- 원본 파일명
    STORE_NM     VARCHAR(120) NOT NULL,    -- 저장 파일명(UUID)
    FILE_SIZE    BIGINT,
    CONTENT_TYPE VARCHAR(150),
    REG_ID       VARCHAR(20),
    REG_DT       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CSR_FILE PRIMARY KEY (FILE_ID)
);

