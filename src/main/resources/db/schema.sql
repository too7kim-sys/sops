-- ① 요청관리 (CSR) -----------------------------------------------------
CREATE TABLE OPS_CSR (
    CSR_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID      VARCHAR(20)   NOT NULL,
    TITLE       VARCHAR(200)  NOT NULL,
    CONTENT     VARCHAR(8000),
    CSR_TYPE    VARCHAR(20)   NOT NULL,   -- 요청 대분류 (CSR_TYPE 코드 : GENERAL/INCIDENT/CHANGE/BACKUP/CONFIG)
    CSR_SUB_TYPE VARCHAR(30),             -- 요청 소분류 (CSR_SUBTYPE 코드, UPPER_CODE=CSR_TYPE)
    PRIORITY    VARCHAR(20),              -- HIGH/MID/LOW
    STATUS      VARCHAR(20)   NOT NULL,   -- REQUESTED/RECEIVED/CLASSIFIED/IN_PROGRESS/PROCESSED/CLOSED/REJECTED
    REQ_ID      VARCHAR(20),              -- 요청자
    REQ_DT      TIMESTAMP,
    DUE_DT      DATE,                     -- 완료요구일
    CHARGER_ID  VARCHAR(20),              -- 처리담당자
    PROC_CONTENT VARCHAR(8000),           -- 처리내용
    PROC_DT     TIMESTAMP,
    LINKED_TYPE VARCHAR(20),              -- INCIDENT/CHANGE (이관 연계)
    LINKED_ID   BIGINT,
    SATISFACTION VARCHAR(10),             -- 만족도(1~5)
    REG_DT      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CSR PRIMARY KEY (CSR_ID)
);
CREATE TABLE OPS_CSR_HIS (
    HIS_ID   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CSR_ID   BIGINT       NOT NULL,
    STATUS   VARCHAR(20)  NOT NULL,
    CONTENT  VARCHAR(8000),
    PROC_ID  VARCHAR(20),
    PROC_DT  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CSR_HIS PRIMARY KEY (HIS_ID)
);

-- 요청 소분류별 요청내용 템플릿 (CSR_SUBTYPE 코드 1:1) ------------------
DROP TABLE IF EXISTS OPS_CSR_TPL;
CREATE TABLE OPS_CSR_TPL (
    SUB_TYPE  VARCHAR(30)  NOT NULL,    -- CSR_SUBTYPE 코드
    CONTENT   VARCHAR(8000),            -- 요청내용 템플릿(리치텍스트)
    LEAD_DAYS INT,                      -- 완료요구일 자동설정용 소요 근무일(영업일)
    USE_AT    CHAR(1)      DEFAULT 'Y',
    REG_DT    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CSR_TPL PRIMARY KEY (SUB_TYPE)
);

-- 요청 ↔ 대상 시스템 (다중 선택, N:M) ----------------------------------
-- OPS_CSR.SYS_ID 는 대표(첫번째) 시스템으로 유지하고 전체 선택은 본 테이블로 관리
DROP TABLE IF EXISTS OPS_CSR_SYS;
CREATE TABLE OPS_CSR_SYS (
    CSR_ID  BIGINT       NOT NULL,
    SYS_ID  VARCHAR(20)  NOT NULL,
    CONSTRAINT PK_OPS_CSR_SYS PRIMARY KEY (CSR_ID, SYS_ID)
);

-- 요청 첨부파일 ---------------------------------------------------------
DROP TABLE IF EXISTS OPS_CSR_FILE;
CREATE TABLE OPS_CSR_FILE (
    FILE_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
