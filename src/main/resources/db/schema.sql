-- 사용자(운영자) ---------------------------------------------------------
CREATE TABLE OPS_USER (
    USER_ID    VARCHAR(20)   NOT NULL,
    USER_NM    VARCHAR(50)   NOT NULL,
    PASSWORD   VARCHAR(100)  NOT NULL,
    ROLE       VARCHAR(20)   NOT NULL,  -- ADMIN / OPERATOR / USER
    POSITN     VARCHAR(30),             -- 직급 (성명(직급) 표기용)
    DEPT_CD    VARCHAR(20),             -- 소속 부서코드(OPS_DEPT.DEPT_CD) — 표시는 부서명으로 조인
    EMAIL      VARCHAR(100),
    TELNO      VARCHAR(20),
    USE_AT     CHAR(1)       DEFAULT 'Y',
    REG_DT     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_USER PRIMARY KEY (USER_ID)
);

-- 응용시스템(운영대상) 마스터 -------------------------------------------
CREATE TABLE OPS_SYSTEM (
    SYS_ID     VARCHAR(20)   NOT NULL,
    SYS_NM     VARCHAR(100)  NOT NULL,
    SYS_DESC   VARCHAR(500),
    MNGR_NM    VARCHAR(50),               -- 운영담당자(성명)
    MNGR_ID    VARCHAR(20),               -- 운영담당자 계정(사용자ID) — 요청 열람·처리 권한
    MNGR_DEPT  VARCHAR(100),              -- 운영부서
    GRAD       VARCHAR(20),               -- 중요도등급 (1~3등급)
    VCS_TYPE      VARCHAR(10) DEFAULT 'GIT', -- 형상관리 유형 (GIT/SVN)
    GIT_URL       VARCHAR(300),           -- 배포 저장소 URL (Git/SVN)
    GIT_BRANCH    VARCHAR(100),           -- 기본 브랜치(Git)/트렁크·경로(SVN)
    DEPLOY_PATH   VARCHAR(300),           -- 배포(체크아웃) 대상 경로
    DEPLOY_SCRIPT VARCHAR(4000),          -- 체크아웃 후 실행 배포 스크립트
    USE_AT     CHAR(1)       DEFAULT 'Y',
    REG_DT     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_SYSTEM PRIMARY KEY (SYS_ID)
);

-- 공통코드 --------------------------------------------------------------
CREATE TABLE OPS_CODE (
    CODE_GRP   VARCHAR(30)   NOT NULL,    -- 코드그룹 (예: INCIDENT_STATUS)
    CODE_ID    VARCHAR(30)   NOT NULL,    -- 코드값
    CODE_NM    VARCHAR(100)  NOT NULL,    -- 코드명
    SORT_ORDR  INT           DEFAULT 1,
    USE_AT     CHAR(1)       DEFAULT 'Y',
    UPPER_CODE VARCHAR(30),               -- 상위코드값(계층코드) : 소분류→대분류 매핑 (예 CSR_SUBTYPE→CSR_TYPE)
    CONSTRAINT PK_OPS_CODE PRIMARY KEY (CODE_GRP, CODE_ID)
);

-- 공통코드 그룹 마스터(그룹코드 → 그룹명)
DROP TABLE IF EXISTS OPS_CODE_GRP;
CREATE TABLE OPS_CODE_GRP (
    GRP_CD     VARCHAR(30)   NOT NULL,    -- 코드그룹코드
    GRP_NM     VARCHAR(100)  NOT NULL,    -- 코드그룹명
    SORT_ORDR  INT           DEFAULT 1,
    USE_AT     CHAR(1)       DEFAULT 'Y',
    CONSTRAINT PK_OPS_CODE_GRP PRIMARY KEY (GRP_CD)
);

-- 장애관리 --------------------------------------------------------------
CREATE TABLE OPS_INCIDENT (
    INC_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID     VARCHAR(20)   NOT NULL,
    TITLE      VARCHAR(200)  NOT NULL,
    CONTENT    VARCHAR(8000),
    SEVERITY   VARCHAR(10)   NOT NULL,    -- 1~4 등급 (1:긴급)
    STATUS     VARCHAR(20)   NOT NULL,    -- RECEIVED/ANALYZING/ACTING/RESOLVED/CLOSED
    OCCR_DT    TIMESTAMP,                 -- 발생일시
    RCPT_DT    TIMESTAMP,                 -- 접수일시
    RESOLVE_DT TIMESTAMP,                 -- 조치완료일시
    CAUSE      VARCHAR(8000),             -- 장애원인
    ACTION     VARCHAR(8000),             -- 조치내용
    CHARGER_ID VARCHAR(20),               -- 처리담당자
