);

-- 변경관리 --------------------------------------------------------------
CREATE TABLE OPS_CHANGE (
    CHG_ID       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SYS_ID       VARCHAR(20)  NOT NULL,
    TITLE        VARCHAR(200) NOT NULL,
    CHG_TYPE     VARCHAR(20)  NOT NULL,   -- PROGRAM/DATABASE/CONFIG/EMERGENCY
    PROC_TYPE    VARCHAR(20),             -- 처리유형(NORMAL/STANDARD/EMERGENCY : 일반/단순/긴급변경)
    REASON       VARCHAR(8000),           -- 변경사유
    CONTENT      VARCHAR(8000),           -- 변경내용
    STATUS       VARCHAR(20)  NOT NULL,   -- REQUESTED/REVIEWING/APPROVED/REJECTED/APPLIED/COMPLETED
    REQ_ID       VARCHAR(20),             -- 요청자
    REQ_DT       TIMESTAMP,               -- 요청일시
    APPR_ID      VARCHAR(20),             -- 승인자
    APPR_DT      TIMESTAMP,               -- 승인일시
    APPR_OPINION VARCHAR(4000),           -- 심의의견
    PLAN_DT      TIMESTAMP,               -- 적용 예정일시(from)
    APPLY_DT     TIMESTAMP,               -- 적용 예정일시(to)
    PROC_RESULT  VARCHAR(8000),           -- 처리 결과(변경 처리 완료 시 기록)
    LINKED_TYPE  VARCHAR(20),             -- 이관 연계 대상(RELEASE/INCIDENT)
    LINKED_ID    BIGINT,                  -- 이관 연계 대상 ID
    PIR_CONTENT  VARCHAR(8000),           -- 이행후검토(PIR) 내용
    PIR_DT       TIMESTAMP,               -- 이행후검토 일시
    REG_DT       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_OPS_CHANGE PRIMARY KEY (CHG_ID)
);

-- 배포(릴리즈)관리 ------------------------------------------------------
